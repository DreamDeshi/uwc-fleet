/**
 * OVERLAY SWEEP at 1440 — every sheet, picker and modal in the requestor and
 * driver flows, opened and photographed.
 *
 * ⚠ THIS HARNESS IS THE DELIVERABLE, NOT THE FIXES. Its job is to answer one
 * question per overlay that source-reading cannot: at 1440, does it cover the
 * form it belongs to, or the primary action?
 *
 * ⚠ IT MUST DISTINGUISH "OPENED AND LOOKS FINE" FROM "NEVER OPENED". A
 * screenshot of an overlay that failed to open is a clean-looking frame of the
 * page behind it, and reporting that as "no problem found" is the failure mode
 * this project has hit repeatedly (see AGENTS.md, ABSENCE LOOKS EXACTLY LIKE
 * SUCCESS). So `capture()` REQUIRES a locator that must be visible first, and
 * records a FAILED-TO-OPEN entry rather than a picture when it is not.
 *
 * Fixture-served: no API, no database, no seeded account.
 *
 *   cd mobile && npx expo start --web --port 8081
 *   cd e2e && npx playwright test overlaySweepShots --config playwright.shots.config.ts
 */

