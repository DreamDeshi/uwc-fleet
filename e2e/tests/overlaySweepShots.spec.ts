// ⚠ RouteType is only { id, name } — the form DERIVES the family and direction
// chips from the NAME (see routeChips in requestor.spec.ts). A fixture named
// just "Customer" renders a family chip and no direction chip, and the run
// stalls waiting for one. Give it the real shape.
const ROUTE_TYPES = [
  { id: "rt-1", name: "Customer Delivery" },
  { id: "rt-2", name: "Customer Return" },
];

async function mockApi(page: Page) {
  await page.route("**/api/v1/**", async (route: Route) => {
    const url = route.request().url();
    const json = (body: unknown) =>
      route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify(body) });

    if (url.includes("/auth/login")) {
      return json({ accessToken: "fixture", refreshToken: "fixture-r", user: REQUESTOR });
    }
    if (url.includes("/users/me") || url.includes("/auth/me")) return json(REQUESTOR);
    if (url.includes("/route-types")) return json(ROUTE_TYPES);
    if (url.includes("/consignees")) return json(CONSIGNEES);
    if (/\/departments(\?|$)/.test(url)) return json([{ id: "dep-1", name: "Logistics" }]);
    if (url.includes("/holidays")) return json([]);
    if (/\/trips(\?|$)/.test(url)) return json([]);
    return json({});
  });
}

async function signIn(page: Page) {
  await mockApi(page);
  await page.goto(APP);
  await page.getByPlaceholder("12-345 6789").fill("123456789");
  await page.getByPlaceholder("Enter your password").fill("fixture");
  await page.getByText("Sign In", { exact: true }).click();
}

/**
 * Photograph an overlay, but ONLY once something inside it is on screen.
 *
 * `proof` is a locator that exists only when the overlay is open. If it never
 * appears, this records a failed-to-open finding and takes a diagnostic shot
 * named `FAILED-*` so the two can never be confused in the output folder.
 */
async function capture(page: Page, name: string, proof: ReturnType<Page["getByText"]>, note = "") {
  try {
    await proof.first().waitFor({ state: "visible", timeout: 12_000 });
  } catch {
    findings.push({ name, opened: false, note: "COULD NOT OPEN — not photographed" });
    await page.screenshot({ path: path.join(SHOTS, `FAILED-${name}.png`) });
    return false;
  }
  await page.waitForTimeout(700);
  await page.screenshot({ path: path.join(SHOTS, `${name}.png`) });
  findings.push({ name, opened: true, note });
  return true;
}

test.use({ viewport: { width: 1440, height: 900 } });

test.describe.configure({ mode: "serial" });

test.beforeAll(() => {
  fs.mkdirSync(SHOTS, { recursive: true });
});

test.afterAll(() => {
  const lines = [
    "# Overlay sweep at 1440",
    "",
    "Generated by `overlaySweepShots.spec.ts`. An entry marked COULD NOT OPEN was",
    "not observed — it is NOT a clean result.",
    "",
    "| overlay | opened | note |",
    "| --- | --- | --- |",
    ...findings.map((f) => `| ${f.name} | ${f.opened ? "yes" : "**NO**"} | ${f.note} |`),
  ];
  fs.writeFileSync(REPORT, lines.join("\n") + "\n", "utf8");
});

test("requestor · pickup picker (wide)", async ({ page }) => {
  await signIn(page);
  await page.getByText("Bookings", { exact: true }).first().waitFor({ timeout: 30_000 });
  await page.getByText("Bookings", { exact: true }).first().click();
  await page.getByLabel("New Booking").click();
  await page.getByText("New Trip Request").waitFor({ timeout: 20_000 });

  // Step 1 — Where. One route type and one consignee in the fixtures.
  await page.getByText("Customer", { exact: true }).first().click();
  await page.getByText("Delivery", { exact: true }).first().click();
  await page.getByPlaceholder("Type company name, area, or location…").fill("Perai");
  // selector-ok: a fixture consignee name, not i18n copy
  const hit = page.getByText("Perai Plastics Sdn Bhd", { exact: true }).locator("visible=true").first();
  await hit.waitFor({ timeout: 10_000 });
  await hit.click();
  await page.getByText("Next", { exact: true }).click();

  // Step 2 — What. One pallet is enough to advance.
  await page.getByText("Cargo Size & Quantity").waitFor({ timeout: 15_000 });
  // selector-ok: the quantity stepper glyph is not a translated string
  await page.getByText("+", { exact: true }).first().click();
  await page.getByText("Next", { exact: true }).click();

  // Step 3 — When. The picker is INLINE here at 1440; there is nothing to open.
  await capture(
    page,
    "requestor-pickup-picker-1440",
    page.getByText("Next: time", { exact: true }),
    "inline wide treatment — no overlay, no dimming"
  );
});
